-- 定时器触发函数：多场景多时间点判断
function x900095_OnCharacterTimer(sceneId, objId, dataId, uTime)
    if not x900095_g_AllBoss[sceneId] then
        return
    end
    
    local currentHour = GetHour()
    local currentMinute = GetMinute()
    local currentTimeKey = currentHour * 60 + currentMinute
    
    local refreshTimes = x900095_g_RefreshTimes[sceneId]
    if not refreshTimes then
        return
    end
    
    for _, timeCfg in ipairs(refreshTimes) do
        local targetTimeKey = timeCfg.hour * 60 + timeCfg.minute
        if currentTimeKey == targetTimeKey then
            x900095_CreateMonster(sceneId)
            break
        end
    end
end

-- BOSS创建函数
function x900095_CreateMonster(sceneId)
    -- 重置消息发送状态
    for _, msgData in pairs(x900095_g_BossSysMsgByGroupID) do
        msgData.isSended = 0
    end
    
    local bossList = x900095_g_AllBoss[sceneId]
    if not bossList then
        return
    end
    
    -- 删除已存在的同IDBOSS
    local monsterCount = GetMonsterCount(sceneId)
    for i = 0, monsterCount - 1 do
        local monsterId = GetMonsterObjID(sceneId, i)
        local monsterDataId = GetMonsterDataID(sceneId, monsterId)
        
        for _, bossData in ipairs(bossList) do
            if monsterDataId == bossData.ID then
                LuaFnDeleteMonster(sceneId, monsterId)
                break
            end
        end
    end
    
    -- 重新创建BOSS
    for _, bossData in ipairs(bossList) do
        local posX = bossData.PosX + random(-5, 5)
        local posY = bossData.PosY + random(-5, 5)
        
        local mstId = LuaFnCreateMonster(
            sceneId, 
            bossData.ID, 
            posX, 
            posY, 
            bossData.BaseAI, 
            bossData.ExtAIScript, 
            bossData.ScriptID
        )
        SetCharacterTitle(sceneId, mstId, bossData.Title)
        x900095_SysMsg(sceneId, bossData.GroupId)
    end
end

-- 副本BOSS创建函数
function x900095_CreateMonsterdange(sceneId)
    if not x900095_g_AllBoss[sceneId] then
        return
    end
    
    -- 重置消息状态
    for _, msgData in pairs(x900095_g_BossSysMsgByGroupID) do
        msgData.isSended = 0
    end
    
    local bossList = x900095_g_AllBoss[sceneId]
    for _, bossData in ipairs(bossList) do
        local isExist = 0
        local monsterCount = GetMonsterCount(sceneId)
        
        -- 检查是否已存在
        for i = 0, monsterCount - 1 do
            local monsterId = GetMonsterObjID(sceneId, i)
            local monsterDataId = GetMonsterDataID(sceneId, monsterId)
            if monsterDataId == bossData.ID then
                isExist = 1
                break
            end
        end
        
        -- 不存在则创建
        if isExist == 0 then
            local posX = bossData.PosX + random(-5, 5)
            local posY = bossData.PosY + random(-5, 5)
            local mstId = LuaFnCreateMonster(
                sceneId, 
                bossData.ID, 
                posX, 
                posY, 
                bossData.BaseAI, 
                bossData.ExtAIScript, 
                bossData.ScriptID
            )
            SetCharacterTitle(sceneId, mstId, bossData.Title)
        end
        
        x900095_SysMsg(sceneId, bossData.GroupId)
    end
end

