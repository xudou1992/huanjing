					AddNumText(sceneId, x002089_g_scriptId, "领取累充"..tostring(x002089_g_PrizeTable[j].point).."奖励", 6, Idx + j);
				end
				else
					AddText(sceneId,"#G未达到隐藏回馈领取要求。")
			end
		EndEvent(sceneId)
		DispatchEventList(sceneId,selfId,targetId)
	end
	if id == 3 then
		BeginEvent(sceneId)
			for i = 22,25 do
				if nExchangePoint >= x002089_g_PrizeTable[i].point then
					nIdx = i;
				end
			end
			if nIdx > 0 then
				for j = 22,nIdx do
					AddNumText(sceneId, x002089_g_scriptId, "领取累充"..tostring(x002089_g_PrizeTable[j].point).."奖励", 6, Idx + j);
				end
				else
					AddText(sceneId,"#G未达到隐藏回馈领取要求。")
			end
		EndEvent(sceneId)
		DispatchEventList(sceneId,selfId,targetId)
	end
	if id >= 200 and id < 1000 then
		local nSelect = id - 200
		BeginEvent(sceneId)
			AddText(sceneId,"当前重数奖励：")
			for i = 1,getn(x002089_g_PrizeTable[nSelect].prize) do
				AddText(sceneId,format("%s *%s个",
				GetItemName(sceneId,x002089_g_PrizeTable[nSelect].prize[i].itemid),
				tostring(x002089_g_PrizeTable[nSelect].prize[i].num)))
			end
			-- if nSelect == 19 then
				-- AddText(sceneId,"自选8888资质宠物一个联系客服领取。")
			-- elseif nSelect == 31 then
				-- AddText(sceneId,"自选12388资质宠物一个联系客服领取。")
			-- end
			AddText(sceneId,"当前充值数：#G"..nExchangePoint)
			AddNumText(sceneId, x002089_g_scriptId, "确认领取",6,nSelect + nPirzeIdx);
		EndEvent(sceneId)
		DispatchEventList(sceneId,selfId,targetId)
	end
	if id >= 1000 then
		if getn(x002089_g_PrizeTable) > 50 then
			x002089_NotifyFailTips( sceneId, selfId, targetId, "表太大了！！！！联系客服解决吧" )
			return
		end
		local nSelect = id - 1000
		if x002089_g_PrizeTable[nSelect] == nil then
			return
		end
		local  nExchangePoint = GetMissionData(sceneId,selfId,CHONG_ZHI_ZENGD) --查询兑换了多少元宝

		if nExchangePoint < x002089_g_PrizeTable[nSelect].point then
			x002089_NotifyFailTips( sceneId, selfId, targetId, "累计充值不足"..x002089_g_PrizeTable[nSelect].point.."点，无法领取。" )
			return
		end
		local nStateIdx = mod(nSelect,10)
		local nMdExIdx = floor(nSelect / 10)
		
		local nStateData = GetMissionData(sceneId,selfId,x002089_g_MDEXIndex[nMdExIdx + 1]);
		local tState = MathCilCompute_1_InEx(nStateData);
		if tState[nStateIdx + 1] == 1 then
			x002089_NotifyFailTips( sceneId, selfId, targetId, "该奖励已经领取" )
			return
		end
		--检测背包够不够
		BeginAddItem(sceneId)
		for i = 1,getn(x002089_g_PrizeTable[nSelect].prize) do
			 AddBindItem( sceneId,x002089_g_PrizeTable[nSelect].prize[i].itemid,x002089_g_PrizeTable[nSelect].prize[i].num)
		end
		if EndAddItem(sceneId,selfId) <= 0 then
			return
		end
		AddItemListToHuman(sceneId,selfId)
		--标记兑换
		tState[nStateIdx + 1] = 1;
		nStateData = MathCilCompute_1_OutEx(tState)
		SetMissionData(sceneId,selfId,x002089_g_MDEXIndex[nMdExIdx + 1],nStateData);
		x002089_NotifyFailTips( sceneId, selfId, targetId, "奖励已领取，请在背包检查" )
	end

end
function MathCilCompute_1_InEx(nData)
	local nTab = {}
	for i = 1,10 do
		nTab[i] = mod(floor(nData/10 ^ (i - 1)),10)
	end
	return nTab
end
function MathCilCompute_1_OutEx(nData)
	local nFinalData = 0
	for i = 1,10 do
		nFinalData = nFinalData + nData[i] * 10 ^ (i - 1)
	end
	return nFinalData
end
